#include <stddef.h>

char	*ft_strrchr(const char *s, int c)
{
	size_t	len;
	size_t	i;

	len = 0;
	while (s[len] != '\0')
		len++;
	i = len + 1;
	while (i > 0)
	{
		i--;
		if (s[i] == (char)c)
			return ((char *)&s[i]);
	}
	return (NULL);
}
